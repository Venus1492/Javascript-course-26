const i = 1660;

if (i % 2 == 0) {
  console.log(i + ' is even');
}
else {
  console.log(i + ' is odd');
}

if (i < 0) {
  console.log(i + ' is negative')
}
else {
  console.log(i + ' is positive')
}

if (i % 5 == 0) {
  console.log(i + ' is a multiple of 5')
}
else {
  console.log(i + ' is not a multiple of 5')
}

if (i % 10 == 0) {
  console.log(i + ' is a multiple of 10')
}
else {
  console.log(i + ' is not a multiple of 10')
}

if (i < 100) {
  console.log(i + ' is lower than 100')
}

else {
  console.log(i + ' is higher than 100')
}